import React, { useEffect, useState } from 'react';
import { ZionHeader } from './components/ZionHeader';
import { ZionLeftSidebar } from './components/ZionLeftSidebar';
import { ZionRightSidebar } from './components/ZionRightSidebar';
import { EricSearchStrip } from './components/EricSearchStrip';
import { DigitalLegacyForm } from './components/DigitalLegacyForm';
import {
  createEmptyLegacyFormState,
  createInitialEricAdamAnalysis,
  DigitalLegacyFormState,
  DocumentStatus,
  EricAdamAssetAnalysis,
  formatDocumentCode,
  formatRussianTimestamp,
  SignedReceipt,
} from './types/legacy';
import { ArrowRight, FileText, ScrollText, Wallet } from 'lucide-react';

const DRAFT_STORAGE_KEY = 'zion_digital_legacy_draft_v2';

export default function App() {
  const [activeTopNav, setActiveTopNav] = useState<string>('Финансы');
  const [activeLeftNav, setActiveLeftNav] = useState<string>('digital-legacy');
  const [mobileMenuOpen, setMobileMenuOpen] = useState(false);

  // Manual form fields start empty; Block 0 metadata is auto-generated by the system
  const [form, setForm] = useState<DigitalLegacyFormState>(() =>
    createEmptyLegacyFormState(1)
  );
  const [docStatus, setDocStatus] = useState<DocumentStatus>('draft');
  const [signedReceipt, setSignedReceipt] = useState<SignedReceipt | null>(null);

  // Block 2: Auto-populated from ERIC & ADAM account analysis
  const [assetAnalysis, setAssetAnalysis] = useState<EricAdamAssetAnalysis>(() =>
    createInitialEricAdamAnalysis()
  );
  const [isSyncingAssets, setIsSyncingAssets] = useState(false);

  const [ericQuery, setEricQuery] = useState('');
  const [draftSavedMessage, setDraftSavedMessage] = useState<string | null>(null);
  const [hasSavedDraft, setHasSavedDraft] = useState(false);

  useEffect(() => {
    try {
      const saved = localStorage.getItem(DRAFT_STORAGE_KEY);
      if (saved) {
        setHasSavedDraft(true);
      }
    } catch {
      // Ignore storage errors
    }
  }, []);

  const handleRefreshEricAdam = () => {
    setIsSyncingAssets(true);
    setTimeout(() => {
      const now = new Date();
      setAssetAnalysis((prev) => ({
        ...prev,
        syncedAt: formatRussianTimestamp(now),
      }));
      setIsSyncingAssets(false);
    }, 450);
  };

  const handleSaveDraft = () => {
    try {
      localStorage.setItem(DRAFT_STORAGE_KEY, JSON.stringify(form));
      setHasSavedDraft(true);
      setDraftSavedMessage(
        'Черновик распоряжения сохранён локально. Поля можно продолжить заполнять или подписать позже.'
      );
      setTimeout(() => setDraftSavedMessage(null), 4000);
    } catch {
      setDraftSavedMessage('Черновик зафиксирован в текущей сессии.');
      setTimeout(() => setDraftSavedMessage(null), 4000);
    }
  };

  const handleRestoreDraft = () => {
    try {
      const raw = localStorage.getItem(DRAFT_STORAGE_KEY);
      if (!raw) return;
      const parsed = JSON.parse(raw) as DigitalLegacyFormState;
      if (parsed && Array.isArray(parsed.beneficiaries)) {
        setForm({
          ...parsed,
          documentNumber: formatDocumentCode(parsed.versionNumber || 1),
          createdDate: parsed.createdDate || formatRussianTimestamp(),
        });
        setDraftSavedMessage('Сохранённый черновик восстановлен в форму.');
        setTimeout(() => setDraftSavedMessage(null), 3500);
      }
    } catch {
      // Ignore malformed storage
    }
  };

  const handleResetForm = () => {
    setForm((prev) => createEmptyLegacyFormState(prev.versionNumber));
    setDocStatus('draft');
    setSignedReceipt(null);
    setDraftSavedMessage('Все ручные поля очищены. Системный номер и дата обновлены.');
    setTimeout(() => setDraftSavedMessage(null), 3000);
  };

  const handleSignSuccess = (receipt: SignedReceipt) => {
    setSignedReceipt(receipt);
    setDocStatus('signed');
    window.scrollTo({ top: 0, behavior: 'smooth' });
  };

  const handleCreateNewVersion = () => {
    const now = new Date();
    setDocStatus('draft');
    setSignedReceipt(null);
    setForm((prev) => {
      const nextVersion = prev.versionNumber + 1;
      return {
        ...prev,
        versionNumber: nextVersion,
        documentNumber: formatDocumentCode(nextVersion, now),
        createdDate: formatRussianTimestamp(now),
        signatureKey: '',
        confirmSmartContractAudit: false,
      };
    });
  };

  const jumpToSection = (sectionId: string) => {
    setActiveLeftNav('digital-legacy');
    setTimeout(() => {
      const el = document.getElementById(sectionId);
      if (el) {
        el.scrollIntoView({ behavior: 'smooth', block: 'start' });
      }
    }, 50);
  };

  const handleSelectLeftNav = (navId: string) => {
    setActiveLeftNav(navId);
    setMobileMenuOpen(false);
    if (navId === 'digital-legacy') {
      setActiveTopNav('Финансы');
    }
  };

  const handleEricSubmit = () => {
    setActiveLeftNav('digital-legacy');
  };

  return (
    <div className="min-h-screen bg-[#F6F4EF] text-[#2A241E] flex flex-col">
      <ZionHeader
        activeTopNav={activeTopNav}
        onSelectTopNav={(item) => {
          setActiveTopNav(item);
          if (item === 'Финансы') {
            setActiveLeftNav('digital-legacy');
          }
        }}
        onOpenMobileMenu={() => setMobileMenuOpen((v) => !v)}
        isMobileMenuOpen={mobileMenuOpen}
        documentStatus={docStatus}
        onJumpToSection={jumpToSection}
      />

      {/* Mobile Sidebar Drawer */}
      {mobileMenuOpen && (
        <div className="fixed inset-0 z-50 lg:hidden flex">
          <div
            className="fixed inset-0 bg-black/30 backdrop-blur-[1px]"
            onClick={() => setMobileMenuOpen(false)}
          />
          <div className="relative z-10 w-[260px] max-w-[85vw] bg-[#F6F4EF] h-full overflow-y-auto p-3 shadow-xl">
            <ZionLeftSidebar
              activeNav={activeLeftNav}
              onSelectNav={handleSelectLeftNav}
              documentStatus={docStatus}
            />
          </div>
        </div>
      )}

      {/* Main Three-Column ZION.CITY Desktop Layout */}
      <div className="flex-1 w-full max-w-[1480px] mx-auto px-3 sm:px-5 py-4 sm:py-5">
        <div className="flex flex-col lg:flex-row items-start gap-4 sm:gap-5">
          {/* Left Navigation Sidebar */}
          <div className="hidden lg:block sticky top-20">
            <ZionLeftSidebar
              activeNav={activeLeftNav}
              onSelectNav={handleSelectLeftNav}
              documentStatus={docStatus}
            />
          </div>

          {/* Center Main Workspace */}
          <main className="flex-1 min-w-0 w-full">
            <EricSearchStrip
              query={ericQuery}
              onQueryChange={setEricQuery}
              onSubmitQuery={handleEricSubmit}
              onQuickJump={jumpToSection}
            />

            {activeLeftNav === 'digital-legacy' ? (
              <div className="space-y-3">
                {/* Optional Draft Restore Prompt (only appears if user previously saved a draft) */}
                {hasSavedDraft && docStatus === 'draft' && (
                  <div className="bg-[#FCFBF8] border border-[#EAE4D7] rounded-xl px-4 py-2.5 flex flex-wrap items-center justify-between gap-2 text-xs">
                    <span className="text-[#6B6155]">
                      Обнаружен ранее сохранённый локальный черновик. Все ручные поля сейчас пусты.
                    </span>
                    <button
                      type="button"
                      onClick={handleRestoreDraft}
                      className="font-semibold text-[#B57619] hover:text-[#8C520C] underline underline-offset-2 whitespace-nowrap"
                    >
                      Загрузить сохранённый черновик
                    </button>
                  </div>
                )}

                <DigitalLegacyForm
                  form={form}
                  status={docStatus}
                  assetAnalysis={assetAnalysis}
                  isSyncingAssets={isSyncingAssets}
                  signedReceipt={signedReceipt}
                  searchFilter={ericQuery}
                  onChange={setForm}
                  onRefreshEricAdam={handleRefreshEricAdam}
                  onSaveDraft={handleSaveDraft}
                  onResetForm={handleResetForm}
                  onSignSuccess={handleSignSuccess}
                  onCreateNewVersion={handleCreateNewVersion}
                  draftSavedMessage={draftSavedMessage}
                />
              </div>
            ) : (
              /* Clean Ecosystem Context View */
              <div className="bg-white border border-[#EAE6DF] rounded-2xl p-6 shadow-[0_1px_4px_rgba(42,36,30,0.04)] space-y-5">
                <div className="flex items-center gap-3 pb-4 border-b border-[#F1EDE4]">
                  <div className="w-10 h-10 rounded-xl bg-[#FEF3C7] text-[#D97706] flex items-center justify-center shrink-0">
                    {activeLeftNav === 'wallet' ? (
                      <Wallet className="w-5 h-5" />
                    ) : (
                      <FileText className="w-5 h-5" />
                    )}
                  </div>
                  <div>
                    <h2 className="text-[18px] font-bold text-[#2A241E]">
                      {activeLeftNav === 'wallet'
                        ? 'Мой Кошелёк — связь с Digital Legacy'
                        : activeLeftNav === 'documents'
                          ? 'Документы участника ZION.CITY'
                          : 'Раздел экосистемы ZION.CITY'}
                    </h2>
                    <p className="text-xs text-[#786E62]">
                      Управление электронным распоряжением о цифровом наследии доступно в разделе «Документы» и «Финансы»
                    </p>
                  </div>
                </div>

                <div className="bg-[#FAF8F4] border border-[#EAE4D7] rounded-xl p-5 flex flex-col sm:flex-row sm:items-center justify-between gap-4">
                  <div className="flex items-start gap-3">
                    <div className="w-9 h-9 rounded-lg bg-[#FEF3C7] border border-[#F3D78D] flex items-center justify-center text-[#B57619] shrink-0">
                      <ScrollText className="w-4 h-4" />
                    </div>
                    <div className="space-y-1">
                      <h3 className="text-sm font-bold text-[#2A241E]">
                        Распоряжение о цифровом наследии (Digital Legacy)
                      </h3>
                      <p className="text-xs text-[#6B6155] max-w-xl leading-relaxed">
                        Заполните электронное распоряжение вручную для распределения ALTYN TOKEN (AT) и ALTYN COIN (AC), назначения наследников и фиксации условий активации через ERIC и ADAM.
                      </p>
                    </div>
                  </div>

                  <button
                    type="button"
                    onClick={() => setActiveLeftNav('digital-legacy')}
                    className="inline-flex items-center gap-2 px-4 py-2.5 rounded-xl bg-gradient-to-b from-[#F59E0B] to-[#D97706] text-white text-xs font-semibold shadow-sm hover:brightness-105 transition-all whitespace-nowrap shrink-0"
                  >
                    <span>Перейти к заполнению</span>
                    <ArrowRight className="w-4 h-4" />
                  </button>
                </div>
              </div>
            )}
          </main>

          {/* Right Utility & Financial Zone Sidebar */}
          <div className="w-full lg:w-auto lg:sticky lg:top-20">
            <ZionRightSidebar />
          </div>
        </div>
      </div>
    </div>
  );
}
